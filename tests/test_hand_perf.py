def _animators():
    song = load_song(midi_path("demo_song.mid"))
    hs = {h: HandAnimator(song, h) for h in ("R", "L")}
    pair_hands(hs.values())
    return hs


def _keyboard():
    import pygame
    from common import Keyboard, bottom_layout
    pygame.init()
    return Keyboard(bottom_layout((1600, 900))[0])


def test_pose_matches_baseline(screen=None):
    kb = _keyboard()
    hs = _animators()
    for (h, t), (w0, arch0, tips0) in BASELINE.items():
        a = hs[h]
        pose = a.pose(t, kb)
        w = pose["wrist"]
        assert abs(w[0] - w0[0]) < 0.5 and abs(w[1] - w0[1]) < 0.5, (h, t, w, w0)
        arch = a.arch_at(t)
        for f, v0 in arch0.items():
            assert abs(arch[f] - v0) < 0.5, (h, t, f, arch[f], v0)
        chains = pose["struct"]["chains"]
        for f, p0 in tips0.items():
            p = chains[f][-1]
            assert all(abs(x - y) < 0.5 for x, y in zip(p, p0)), (h, t, f, p, p0)


def test_pose_60_frames_is_fast():
    kb = _keyboard()
    hs = _animators()
    t0 = time.perf_counter()
    for t in range(60):
        for h in hs.values():
            h.pose(t / 30.0, kb)
    dt = time.perf_counter() - t0
    print(f"\n60 frames x 2 hands posed in {dt:.2f}s")
    # Pre-optimization baseline on the dev machine: ~4.1s. Must stay well under
    # half of that; generous bound so slower CI machines don't flake.
    assert dt < 2.5, f"pose too slow: {dt:.2f}s for 60 frames x 2 hands"
